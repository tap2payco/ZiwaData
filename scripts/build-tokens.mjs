// Generates src/styles/tokens.css from design/bwawa-tokens.json.
// Run: npm run tokens  (also runs before dev and build)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'design/bwawa-tokens.json'), 'utf8'));
const out = resolve(root, 'src/styles/tokens.css');

const themes = src.color.themes.map((t) => t.id); // light, dark, sun
const lines = [];
lines.push('/* GENERATED by scripts/build-tokens.mjs from design/bwawa-tokens.json. Do not edit by hand. */');

// Fonts (bundled locally in public/fonts, never a CDN)
for (const f of src.type.fonts) {
  const file = f.file.replace(/^fonts\//, '/fonts/');
  lines.push(
    `@font-face { font-family: "${f.family}"; src: url("${file}") format("woff2"); font-weight: ${f.weight}; font-style: ${f.style}; font-display: swap; }`,
  );
}
lines.push('');

const shared = [];
shared.push(`--font-sans: ${src.type.families.sans};`);
shared.push(`--font-mono: ${src.type.families.mono};`);
for (const g of ['spacing', 'radius', 'size']) {
  for (const t of src[g].tokens) shared.push(`--${t.name}: ${t.value};`);
}
// Stroke widths: tokens are named stroke-control / stroke-focus / stroke-sun.
for (const g of src.type.groups) {
  for (const s of g.styles) {
    shared.push(`--fs-${s.name}: ${s.fontSize};`, `--lh-${s.name}: ${s.lineHeight};`, `--fw-${s.name}: ${s.fontWeight};`);
  }
}

function themeVars(id) {
  const v = [];
  for (const t of src.color.tokens) v.push(`--${t.name}: ${t.value[id]};`);
  for (const t of src.shadow.tokens) v.push(`--${t.name}: ${t.value[id]};`);
  return v;
}

lines.push(`:root { ${shared.join(' ')} }`);
lines.push('');
for (const id of themes) {
  // Light is also the fallback when data-theme is missing.
  const sel = id === 'light' ? ':root, [data-theme="light"]' : `[data-theme="${id}"]`;
  lines.push(`${sel} {\n  ${themeVars(id).join('\n  ')}\n  color-scheme: ${id === 'dark' ? 'dark' : 'light'};\n}`);
  lines.push('');
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(`tokens.css written: ${src.color.tokens.length} colours x ${themes.length} themes`);
